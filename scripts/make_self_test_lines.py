"""Render the two printed lines of the model self-test and write src/folio_ocr/model_self_test_lines.py.

Development only. Needs the dev extras (fpdf2, uharfbuzz, fonttools) and pypdfium2. Run:
    python scripts/make_self_test_lines.py
"""

from __future__ import annotations

import base64
import hashlib
import io
import os
import re
import subprocess
import sys
from pathlib import Path

import numpy as np
from fixture_fonts import font_path
from fixture_images import INK_LEVEL, render_pdf
from fixture_pages import blank_pdf
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "src" / "folio_ocr" / "model_self_test_lines.py"
PAGE_W, PAGE_H, FONT_PT, GROW = 420, 40, 14, 12
ENGLISH = "Invoice number: INV-2026-3706"
ARABIC_CODE_POINTS = (
    *(0x0631, 0x0642, 0x0645, 0x20),
    *(0x0627, 0x0644, 0x0641, 0x0627, 0x062A, 0x0648, 0x0631, 0x0629, 0x20),
    *(0x0661, 0x0662, 0x0663, 0x0664),
)
ARABIC = "".join(map(chr, ARABIC_CODE_POINTS))
# (key, text, font key, fallback font key, alignment)
SPECS = (("en", ENGLISH, "sans", None, "L"), ("ar", ARABIC, "amiri", "sans", "R"))


def _draw(text: str, font: str, fallback: str | None, align: str) -> Image.Image:
    pdf = blank_pdf(PAGE_W, PAGE_H)
    pdf.add_font("main", fname=str(font_path(font)))
    if fallback is not None:
        pdf.add_font("fallback", fname=str(font_path(fallback)))
    pdf.set_text_shaping(True)
    if fallback is not None:
        pdf.set_fallback_fonts(["fallback"])
    pdf.add_page()
    pdf.set_font("main", size=FONT_PT)
    pdf.set_xy(10, 0)
    pdf.cell(PAGE_W - 20, PAGE_H, text, align=align)
    return render_pdf(bytes(pdf.output()))


def _crop_to_ink(img: Image.Image) -> Image.Image:
    ink = np.asarray(img) < INK_LEVEL
    rows, cols = np.nonzero(ink.any(axis=1))[0], np.nonzero(ink.any(axis=0))[0]
    if not len(rows):
        raise ValueError("the line drew no ink")
    box = (
        max(0, int(cols[0]) - GROW),
        max(0, int(rows[0]) - GROW),
        min(img.width, int(cols[-1]) + 1 + GROW),
        min(img.height, int(rows[-1]) + 1 + GROW),
    )
    return img.crop(box)


def _png(img: Image.Image) -> bytes:
    buf = io.BytesIO()
    img.convert("L").save(buf, "PNG", optimize=True)
    return buf.getvalue()


def render_lines() -> dict[str, bytes]:
    """The PNG bytes of each line, keyed by language ("en", "ar")."""
    return {k: _png(_crop_to_ink(_draw(t, f, fb, a))) for k, t, f, fb, a in SPECS}


def _wrapped(data: bytes, indent: str = "    ") -> str:
    text = base64.b64encode(data).decode("ascii")
    pieces = [text[i : i + 80] for i in range(0, len(text), 80)]
    return "\n".join(f'{indent}"{p}"' for p in pieces)


def _text_source(text: str) -> str:
    if text.isascii():
        return repr(text)
    return '"".join(map(chr, (' + ", ".join(f"0x{ord(c):04X}" for c in text) + ",)))"


def module_source(png: dict[str, bytes]) -> str:
    parts = [
        '''"""Two printed lines the model self-test reads: one English, one Arabic with Arabic-Indic digits.

Generated by scripts/make_self_test_lines.py; do not edit by hand."""

import base64
import hashlib
from dataclasses import dataclass


@dataclass(frozen=True)
class SelfTestLine:
    languages: str
    text: str
    png: bytes
    sha256: str


def _line(languages: str, text: str, encoded: str) -> SelfTestLine:
    data = base64.b64decode(encoded, validate=True)
    return SelfTestLine(languages, text, data, hashlib.sha256(data).hexdigest())

'''
    ]
    for key, text, *_ in SPECS:
        parts.append(f"_{key.upper()}_PNG = (\n{_wrapped(png[key])}\n)\n")
        parts.append(f"_{key.upper()}_TEXT = {_text_source(text)}\n")
    parts.append(
        "\nLINES: tuple[SelfTestLine, ...] = (\n"
        '    _line("en", _EN_TEXT, _EN_PNG),\n'
        '    _line("ar", _AR_TEXT, _AR_PNG),\n)\n'
    )
    return "\n".join(parts)


def _tesseract_read(data: bytes, lang: str) -> str | None:
    from folio_ocr.config import Settings, find_tesseract

    settings = Settings.from_env(os.environ)
    program, tessdata = find_tesseract(settings), settings.weights_dir / "tessdata"
    if program is None or not tessdata.is_dir():
        return None
    cmd = [str(program), "stdin", "stdout", "--tessdata-dir", str(tessdata)]
    done = subprocess.run(
        [*cmd, "-l", lang, "--psm", "7"], input=data, capture_output=True, timeout=60, check=True
    )
    return re.sub(r"\s+", " ", done.stdout.decode("utf-8")).strip()


def main() -> int:
    png = render_lines()
    OUTPUT.write_text(module_source(png), encoding="utf-8", newline="\n")
    subprocess.run([sys.executable, "-m", "ruff", "format", str(OUTPUT)], check=True)
    for (key, text, *_), lang in zip(SPECS, ("eng", "ara"), strict=True):
        size = Image.open(io.BytesIO(png[key])).size
        read = _tesseract_read(png[key], lang)
        print(key, size, len(png[key]), hashlib.sha256(png[key]).hexdigest())
        print("  tesseract:", ascii(read), "exact" if read == text else "DIFFERS")
    return 0


if __name__ == "__main__":
    sys.exit(main())
